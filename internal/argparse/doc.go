// Package argparse reproduces Python 3.15 argparse for the subset of features the
// niagara-research tools use, with byte-identical help, usage, error text and exit codes.
//
// The API mirrors argparse: New(Config) is ArgumentParser(...), Parser.Add(Arg, names...)
// is add_argument, AddSubparsers/AddParser, AddMutuallyExclusiveGroup, AddArgumentGroup,
// SetDefaults, and Parse is parse_args returning (namespace, exit code, done). When done
// is true, help, a version or a usage error was already written and the tool exits with
// the code. Help width follows shutil.get_terminal_size: $COLUMNS, else the terminal,
// else 80, minus 2. Colour output is never produced.
//
// testdata/fixtures.json, regenerated by `python3 -I internal/argparse/testdata/gen_fixtures.py`,
// pins the behaviour: each case is a declarative parser spec, an argv and COLUMNS, and the
// stdout, stderr, exit status and namespace Python produced. docs/argparse.md lists the
// surveyed features and the known gaps.
package argparse
